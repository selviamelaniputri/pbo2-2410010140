private void simpan() {
    String kode = kodeField.getText().trim();
    String judul = judulField.getText().trim();
    String penulis = penulisField.getText().trim();
    String tahunTeks = tahunField.getText().trim();
    String status = (String) statusCombo.getSelectedItem();

    if (kode.isEmpty()) {
        pesanLabel.setText("Kode buku wajib diisi.");
        kodeField.requestFocus();
        return;
    }

    if (judul.isEmpty()) {
        pesanLabel.setText("Judul buku wajib diisi.");
        judulField.requestFocus();
        return;
    }

    if (penulis.isEmpty()) {
        pesanLabel.setText("Nama penulis wajib diisi.");
        penulisField.requestFocus();
        return;
    }

    int tahun;

    try {
        tahun = Integer.parseInt(tahunTeks);
    } catch (NumberFormatException e) {
        pesanLabel.setText("Tahun harus berupa angka.");
        tahunField.requestFocus();
        return;
    }

    int tahunSekarang = java.time.Year.now().getValue();

    if (tahun < 1900 || tahun > tahunSekarang) {
        pesanLabel.setText(
                "Tahun harus antara 1900 dan " + tahunSekarang
        );
        tahunField.requestFocus();
        return;
    }

    hasil = new Buku(kode, judul, penulis, tahun, status);
    dispose();
}

