    private void tambah() {
    DialogBuku dialog = new DialogBuku(
        this,
        "Tambah Buku",
        null
    );

    Buku hasil = dialog.tampilkan();

    if (hasil != null) {
        model.tambah(hasil);
        perbaruiStatus();
    }
}
    
    private void ubah() {
    int barisView = bukuTable.getSelectedRow();

    if (barisView == -1) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Pilih buku yang ingin diubah terlebih dahulu.",
                "Peringatan",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    int barisModel = bukuTable.convertRowIndexToModel(barisView);

    Buku bukuLama = model.get(barisModel);

    DialogBuku dialog = new DialogBuku(
            this,
            "Ubah Buku",
            bukuLama
    );

    Buku hasil = dialog.tampilkan();

   if (hasil != null) {
    model.ubah(barisModel, hasil);
    perbaruiStatus();
}
}
    
    private void hapus() {
    int barisView = bukuTable.getSelectedRow();

    if (barisView == -1) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Pilih buku yang ingin dihapus terlebih dahulu.",
                "Peringatan",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    int konfirmasi = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "Apakah Anda yakin ingin menghapus buku ini?",
            "Konfirmasi Hapus",
            javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (konfirmasi == javax.swing.JOptionPane.YES_OPTION) {
    int barisModel = bukuTable.convertRowIndexToModel(barisView);

    model.hapus(barisModel);
    perbaruiStatus();
    perbaruiTombol();
}
}
    
    private void saring() {
    String teks = cariField.getText().trim();

    javax.swing.table.TableRowSorter<?> sorter =
            (javax.swing.table.TableRowSorter<?>) bukuTable.getRowSorter();

    if (teks.isEmpty()) {
        sorter.setRowFilter(null);
    } else {
        sorter.setRowFilter(
                javax.swing.RowFilter.regexFilter(
                        "(?i)" + java.util.regex.Pattern.quote(teks),
                        0, 1, 2
                )
        );
    }

    statusLabel.setText(
            "Menampilkan " + bukuTable.getRowCount()
            + " dari " + model.getRowCount() + " buku"
    );
}
    
