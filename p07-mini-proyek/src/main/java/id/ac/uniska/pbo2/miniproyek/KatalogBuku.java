private void perbaruiStatus() {
    int totalBuku = model.getRowCount();
    int tersedia = 0;

    for (int i = 0; i < totalBuku; i++) {
        if ("Tersedia".equals(model.get(i).getStatus())) {
            tersedia++;
        }
    }

    statusLabel.setText(
        "Menampilkan " + bukuTable.getRowCount()
        + " dari " + totalBuku
        + " buku | Tersedia: " + tersedia
    );
}
 
